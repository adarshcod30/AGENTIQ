/**
 * Renders docs/90_EVALUATION.md from the harness's raw observations.
 *
 * docs/01_PRD.md F10: "Whatever the number is, report it: a measured 61% is a
 * stronger result than an unmeasured claim of success." Nothing in here styles
 * a bad number as a good one, and every table states its denominator so a
 * reader can check the arithmetic.
 */
import { FAMILIES } from './targets.js';
import { MUTANTS } from './mutants.js';
import { pct } from './lib.js';

const n = (v) => (v === null || v === undefined ? 'n/a' : String(v));

export function renderReport({ security, mutation, meta }) {
  const L = [];
  const w = (...lines) => L.push(...lines);

  w(
    '# Evaluation',
    '',
    '> **Generated by `npm run evaluate`. Do not edit by hand.**  ',
    `> Produced ${meta.generatedAt} · node ${meta.node} · ` +
      (meta.commit ? `commit \`${meta.commit}\` · ` : '') +
      `${meta.durationSec}s wall clock`,
    '',
    'Every number below was measured by running the real agents through the real MCP tool',
    'layer: the same permission gate, SSRF egress guard and audit writer the product uses.',
    'The harness is `evaluation/`, the ground-truth labels are `evaluation/targets.js`, and the',
    'raw observations are committed alongside this file in `evaluation/results/`.',
    '',
    '---',
    '',
  );

  /* ── 1 ── */
  w(
    '## 1 · Security detection',
    '',
    'Two fixture applications with **identical routes, seed data and response contracts**,',
    'differing only in their defects (`fixtures/shared/data.js` is shared by both, and',
    '`fixtures/tests/contract.test.js` fails the build if they ever diverge). Because the apps',
    'are otherwise the same, a finding on one and not the other can only be explained by the',
    'defect, which is what makes these numbers interpretable.',
    '',
    `Each of ${security.observations.length / 2 / FAMILIES.length} endpoints was scanned on both apps ` +
      `across all ${FAMILIES.length} families, giving **${security.observations.length} labelled observations**.`,
    '',
    '| Family | TP | FP | FN | TN | Precision | Recall | F1 |',
    '| --- | --: | --: | --: | --: | --: | --: | --: |',
  );
  for (const f of FAMILIES) {
    const s = security.perFamily[f];
    w(`| \`${f}\` | ${s.TP} | ${s.FP} | ${s.FN} | ${s.TN} | ${pct(s.precision)} | ${pct(s.recall)} | ${pct(s.f1)} |`);
  }
  const o = security.overall;
  w(`| **overall** | **${o.TP}** | **${o.FP}** | **${o.FN}** | **${o.TN}** | **${pct(o.precision)}** | **${pct(o.recall)}** | **${pct(o.f1)}** |`);

  w(
    '',
    '### False positives on the hardened application',
    '',
    'The hardened app is not vulnerable to anything, by construction. Any finding against it is',
    'therefore wrong, which makes this the honest counterweight to recall: a scanner that',
    'reported everything on everything would score 100% recall and be useless.',
    '',
    `**Measured false-positive rate: ${pct(security.hardenedFalsePositiveRate)}**`,
    `(${security.falsePositives.length} finding(s) across ${security.observations.filter((x) => x.variant === 'hardened').length} hardened observations)`,
    '',
  );
  if (security.falsePositives.length === 0) {
    w(
      'No false positives. The control that produces this result is the `intendedPublic`',
      'declaration: three of the four endpoints are meant to be reachable anonymously, so an',
      'anonymous 200 there is correct behaviour rather than broken authentication. Without that',
      'declaration, every public endpoint would carry an auth finding.',
      '',
    );
  } else {
    w('Each one is a defect in the scanner, listed so it can be fixed rather than averaged away:', '');
    for (const fp of security.falsePositives) w(`- \`${fp}\``);
    w('');
  }

  /* ── 2 ── */
  const g = mutation.byMode.grounded;
  const u = mutation.byMode.ungrounded;

  w(
    '---',
    '',
    '## 2 · Test-generation adequacy (mutation score)',
    '',
    'Adapted from the mutation-score methodology of **RESTestBench** (arXiv 2604.25862).',
    '',
    '**The adaptation, stated plainly.** Classical mutation testing edits the source and asks',
    'whether the suite notices. Here the suite is a set of HTTP requests with assertions, so the',
    'only thing it can observe is the *response*. A source edit that changes no response is',
    'unkillable by any black-box API suite, and counting such mutants would drag every tool',
    'toward zero without distinguishing between them. Each mutant here therefore injects one',
    'deviation at the **response boundary** of the hardened app, so every mutant is observable in',
    'principle and "did the suite kill it?" is a question about the suite rather than about',
    'reachability.',
    '',
    `**${MUTANTS.length} mutants** across the four categories named in the PRD:`,
    '',
    '| Mutant | Category | Behaviour |',
    '| --- | --- | --- |',
  );
  for (const m of MUTANTS) w(`| \`${m.id}\` | ${m.category} | ${m.title} |`);

  w(
    '',
    'A mutant counts as **killed** only when an assertion that *passed against the unmutated app*',
    '*fails* against the mutant. Comparing to that baseline is what stops an already-broken',
    'assertion from being credited with a kill it did not earn.',
    '',
    '**Only applicable mutants are scored.** Each mutant declares the endpoints it can affect. A',
    'suite generated for `/users/1` sends no request to `/items`, so an `/items` mutant is',
    'unkillable by it; counting such pairs as survivals would measure endpoint coverage while',
    'claiming to measure assertion quality. Scoring all 8 mutants against all 8 suites produced a',
    'mutation score of 6.3% that said almost nothing about the generator.',
    '',
    `Each arm was run **${g.repeats}×** and the mean is reported, because generation is stochastic and`,
    'a single sample can put noise in a results table and call it a finding.',
    '',
    '| | Grounded | Description-only |',
    '| --- | --: | --: |',
    `| Repeats | ${g.repeats} | ${u.repeats} |`,
    `| Generation success rate | ${pct(g.generationSuccessRate)} | ${pct(u.generationSuccessRate)} |`,
    `| Suites generated | ${g.suites} | ${u.suites} |`,
    `| Cases generated | ${g.casesGenerated} | ${u.casesGenerated} |`,
    `| Cases discarded | ${g.casesDiscarded} | ${u.casesDiscarded} |`,
    `| Assertions | ${g.assertions} | ${u.assertions} |`,
    `| Baseline pass rate | ${pct(g.baselinePassRate)} | ${pct(u.baselinePassRate)} |`,
    `| Mutants evaluated | ${g.mutantsEvaluated} | ${u.mutantsEvaluated} |`,
    `| Mutants killed | ${g.mutantsKilled} | ${u.mutantsKilled} |`,
    `| **Mutation score (mean)** | **${pct(g.mutationScore)}** | **${pct(u.mutationScore)}** |`,
    `| Observed range | ${pct(g.scoreMin)}, ${pct(g.scoreMax)} | ${pct(u.scoreMin)}, ${pct(u.scoreMax)} |`,
    '',
    '### Per-repeat scores',
    '',
    '| Repeat | Grounded | Description-only |',
    '| --: | --: | --: |',
    ...g.perRepeat.map((r, i) => {
      const ur = u.perRepeat[i];
      return `| ${r.repeat} | ${pct(r.score)} (${r.killed}/${r.total}) | ` +
        `${ur ? `${pct(ur.score)} (${ur.killed}/${ur.total})` : 'n/a'} |`;
    }),
    '',
    '### By mutation category',
    '',
    '| Category | Grounded | Description-only |',
    '| --- | --: | --: |',
  );
  const cats = [...new Set([...Object.keys(g.byCategory), ...Object.keys(u.byCategory)])].sort();
  for (const c of cats) {
    const gc = g.byCategory[c];
    const uc = u.byCategory[c];
    w(`| ${c} | ${gc ? `${pct(gc.score)} (${gc.killed}/${gc.total})` : 'n/a'} | ${uc ? `${pct(uc.score)} (${uc.killed}/${uc.total})` : 'n/a'} |`);
  }

  w(
    '',
    '### Surviving mutants',
    '',
    'A surviving mutant is a behaviour the generated suite does not check. These are the most',
    'useful rows in the whole report: they say exactly where generation is weak.',
    '',
    '| Mutant | Grounded kills | Description-only kills |',
    '| --- | --: | --: |',
  );
  for (const m of MUTANTS) {
    const gm = g.byMutant[m.id] ?? { killed: 0, total: 0 };
    const um = u.byMutant[m.id] ?? { killed: 0, total: 0 };
    w(`| \`${m.id}\` ${m.title} | ${gm.killed}/${gm.total} | ${um.killed}/${um.total} |`);
  }

  const neverKilled = MUTANTS.filter((m) => {
    const gm = g.byMutant[m.id];
    const um = u.byMutant[m.id];
    return ((gm?.killed ?? 0) + (um?.killed ?? 0)) === 0 && ((gm?.total ?? 0) + (um?.total ?? 0)) > 0;
  });
  if (neverKilled.length) {
    w(
      '',
      '### Behaviours neither arm ever checked',
      '',
      'These mutants survived **every** run of **both** arms. Each one names a specific assertion',
      'the generator does not write, which makes this the most directly actionable list in the',
      'report:',
      '',
    );
    for (const m of neverKilled) w(`- \`${m.id}\`: ${m.title}. **Requires** ${m.kills}.`);
    w('');
  }

  /* ── 3 ── */
  const d = mutation.ablation.deltaPoints;
  w(
    '',
    '---',
    '',
    '## 3 · Grounding ablation',
    '',
    'The same generator, the same model, the same case count, the same endpoints, the same',
    'mutants and the same execution path. The **only** difference is whether the prompt receives',
    'the parsed OpenAPI operation.',
    '',
    '| | Spec-grounded | Description-only | Delta |',
    '| --- | --: | --: | --: |',
    `| Mean over ${g.repeats} runs | ${pct(mutation.ablation.grounded)} | ${pct(mutation.ablation.ungrounded)} | ` +
      `${d === null ? 'n/a' : `${d > 0 ? '+' : ''}${d} points`} |`,
    `| Range | ${pct(g.scoreMin)}, ${pct(g.scoreMax)} | ${pct(u.scoreMin)}, ${pct(u.scoreMax)} | |`,
    '',
  );
  // Do the two arms' observed ranges overlap? If so, the sign of the delta is
  // not something this benchmark can support a claim about.
  const overlaps = g.scoreMin !== null && u.scoreMin !== null
    && g.scoreMin <= u.scoreMax && u.scoreMin <= g.scoreMax;

  // The repeats are PAIRED: repeat i of each arm ran under identical
  // conditions, so comparing them repeat by repeat is a sharper test than
  // asking whether the two ranges happen to overlap.
  const paired = g.perRepeat.map((r, i) => ({ g: r.score, u: u.perRepeat[i]?.score }))
    .filter((x) => x.g !== null && x.g !== undefined && x.u !== null && x.u !== undefined);
  const wins = paired.filter((x) => x.g > x.u).length;
  const ties = paired.filter((x) => x.g === x.u).length;
  const losses = paired.filter((x) => x.g < x.u).length;

  if (overlaps && d !== null && d !== 0) {
    w(
      `The means differ by ${d > 0 ? '+' : ''}${d} points and **the observed ranges overlap**`,
      `(grounded ${pct(g.scoreMin)} to ${pct(g.scoreMax)}, description-only ` +
        `${pct(u.scoreMin)} to ${pct(u.scoreMax)}), so the ranges alone do not settle it.`,
      '',
      'The repeats are **paired**, though: repeat *i* of each arm ran under identical conditions, ',
      'so the sharper comparison is repeat by repeat:',
      '',
      `- Spec-grounded **won ${wins}**, **tied ${ties}**, **lost ${losses}** of ${paired.length}.`,
      '',
    );
    if (losses === 0 && wins > 0) {
      w(
        `Grounding matched or beat description-only in **every** repeat. With ${paired.length}`,
        'paired runs a clean sweep would happen about one time in eight by chance alone, so this is',
        '**suggestive but not significant**: it points the way F4 predicted without proving it.',
        'More endpoints and more repeats would settle it; that is a limit of the benchmark, not a',
        'finding about grounding.',
        '',
      );
    } else {
      w(
        'That is not a consistent direction, so the honest reading is **no detectable difference at',
        'this sample size**, and the signed delta is reported only so the raw figure is not hidden.',
        '',
      );
    }
    w('',
      'What the per-mutant table does show is more specific than the aggregate, and more useful:',
      'grounding changes *which* behaviours get checked, not how many. Assertions on declared',
      'response fields are the mechanism `docs/01_PRD.md` F4 predicted, and that is visible per',
      'mutant even though it does not move the total.',
      '',
      'To resolve the direction would need more endpoints and more repeats: a limitation of the',
      'benchmark, not a finding about grounding.',
      '',
    );
  } else if (d === null) {
    w('Not computable: one of the two arms produced no evaluable mutants.', '');
  } else if (d > 0) {
    w(
      `Grounding is worth **${d} percentage points** of mutation score on this benchmark. The`,
      'mechanism is visible in the per-category table: a grounded prompt receives the declared',
      'status codes and response fields, so it writes assertions about things the specification',
      'actually promises rather than fields the model imagined.',
      '',
    );
  } else if (d === 0) {
    const gSpread = (g.scoreMax ?? 0) - (g.scoreMin ?? 0);
    const uSpread = (u.scoreMax ?? 0) - (u.scoreMin ?? 0);
    w(
      'Grounding made **no difference to the mean** on this benchmark. That is the result, and it',
      'is reported unchanged.',
      '',
      'The means are equal, but they are not equally trustworthy:',
      '',
      `- **Spec-grounded** varied by ${(gSpread * 100).toFixed(0)} points across repeats ` +
        `(${pct(g.scoreMin)}: ${pct(g.scoreMax)}).`,
      `- **Description-only** varied by ${(uSpread * 100).toFixed(0)} points ` +
        `(${pct(u.scoreMin)}: ${pct(u.scoreMax)}).`,
      '',
    );
    if (gSpread < uSpread) {
      w(
        'So grounding bought **consistency rather than raw score** here. A generator that produces',
        'the same coverage every time is more useful than one that averages the same number by',
        'being lucky half the time, and the per-mutant table above shows where that stability comes',
        'from. This is worth more than the headline: a single run of each arm would have reported a',
        'confident 20-point delta in one direction or the other, purely from sampling noise.',
        '',
      );
    }
    w(
      'These four endpoints may also be simple enough for the description alone to convey the',
      'contract. A larger or less self-evident API would be a fairer test: a limitation of this',
      'benchmark rather than a finding about grounding in general.',
      '',
    );
  } else {
    w(
      `Grounding **reduced** the mutation score by ${Math.abs(d)} percentage points on this`,
      'benchmark. Reported unchanged. A plausible mechanism is that the grounded prompt anchors',
      'generation to declared status codes and so produces narrower assertions; the per-category',
      'table above is where to look for which behaviours stopped being checked.',
      '',
    );
  }

  /* ── 4 ── */
  const gen = mutation.generation;
  const totalTokens = gen.inputTokens + gen.outputTokens;
  w(
    '---',
    '',
    '## 4 · Cost and latency',
    '',
    `Provider: **${meta.provider ?? 'unknown'}** · model \`${meta.model ?? 'unknown'}\``,
    '',
    '| | |',
    '| --- | --: |',
    `| Generation calls | ${gen.calls} |`,
    `| Input tokens | ${gen.inputTokens.toLocaleString()} |`,
    `| Output tokens | ${gen.outputTokens.toLocaleString()} |`,
    `| Total tokens | ${totalTokens.toLocaleString()} |`,
    `| Estimated cost | ${gen.costUsd ? `$${gen.costUsd.toFixed(6)}` : 'below measurable precision'} |`,
    `| Mean generation latency | ${gen.calls ? Math.round(gen.ms / gen.calls) : 0} ms |`,
    `| Total wall clock | ${meta.durationSec} s |`,
    `| Audited tool invocations | ${meta.audit?.total ?? 'n/a'} |`,
    '',
    'Every one of those invocations passed through the permission gate and the SSRF egress guard',
    'and wrote a row to the append-only audit collection. The count is reported because it is the',
    'evidence that this measurement exercised the real tool layer rather than a shortcut around it.',
    '',
    'Cost is per **generation call**; execution and the security scan make no LLM calls at all.',
    'That asymmetry is a design property rather than an accident: the LLM proposes assertions and',
    'the `run_test_case` tool decides pass or fail, so re-running every suite against each mutant',
    'costs nothing beyond HTTP.',
    '',
    '---',
    '',
    '## Threats to validity',
    '',
    '1. **Two fixture applications are not a population.** Every number here describes this',
    '   benchmark. They are a floor for "does the tool work at all", not an estimate of',
    '   real-world performance.',
    '2. **The mutants are response-boundary, not source-level** (§2). This is the right unit for a',
    '   black-box API suite, but it is not what a classical mutation-testing paper measures, and',
    '   the scores are not directly comparable to one.',
    '3. **The ground-truth labels were written from the fixtures\' defect comments**, before the',
    '   scanner was run against them. Had they been adjusted to match the output, the measurement',
    '   would be circular.',
    `4. **Generation is stochastic.** Each arm was run ${g.repeats}× and the mean is reported with`,
    '   its observed range. That is enough to show whether a difference is robust to resampling,',
    '   but it is not a significance test, and the ranges overlap often enough that a small delta',
    '   should not be read as a reliable effect.',
    `5. **${g.generationFailures + u.generationFailures} of ` +
    `${g.suitesAttempted + u.suitesAttempted} suite generations failed outright** after ` +
    '   3 attempts each, and are recorded rather than retried indefinitely. A failed generation',
    '   contributes no mutants to the denominator, so it lowers coverage without inflating or',
    '   deflating the score.',
    '6. **The security scan detects indicators, not exploits.** A `rate` finding in particular is',
    '   an absence of evidence of throttling across 8 requests, which a generous limiter would',
    '   also permit. It is scored MEDIUM for that reason.',
    '',
  );

  return L.join('\n');
}
